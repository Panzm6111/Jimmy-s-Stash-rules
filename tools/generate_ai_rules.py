#!/usr/bin/env python3
"""Render reviewed AI domain selections; never import upstream categories wholesale."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'research/ai-sources.json'
OUTPUT = ROOT / 'rules/openai.yaml'  # Keep existing public URL stable.


def convert(entry: str) -> str:
    """Only exact and suffix host rules are approved for this Stash rule provider."""
    kind = 'DOMAIN' if entry.startswith('full:') else 'DOMAIN-SUFFIX'
    host = entry.removeprefix('full:')
    if not re.fullmatch(r'[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?', host) or '.' not in host:
        raise ValueError(f'unreviewed AI source entry: {entry}')
    if any(not label or label.startswith('-') or label.endswith('-') for label in host.split('.')):
        raise ValueError('invalid hostname')
    return kind + ',' + host


def selected_rules(manifest: dict) -> list[str]:
    result = []
    for source in manifest['sources']:
        selected = source['selected']
        if not selected or set(selected).intersection(source['omitted']):
            raise ValueError('AI selection must be nonempty and disjoint from omissions')
        result.extend(convert(entry) for entry in selected)
    for item in manifest['local_rules']:
        if item['rule'].split(',', 1)[0] not in {'DOMAIN', 'DOMAIN-SUFFIX'}:
            raise ValueError('unreviewed local AI rule')
        result.append(item['rule'])
    return list(dict.fromkeys(result))


def rendered(manifest: dict | None = None) -> str:
    manifest = manifest or json.loads(MANIFEST.read_text())
    header = ('# Overseas AI domain rules; retained stable path: rules/openai.yaml.\n'
              '# Reviewed subsets of v2fly/domain-list-community (MIT); local additions: MIT.\n'
              '# See research/ai-sources.json and licenses/v2fly-domain-list-community-MIT.txt.\n'
              '# Generated by tools/generate_ai_rules.py; no shared CDN / global Google or Microsoft rules.\n')
    return header + yaml.safe_dump({'payload': selected_rules(manifest)}, allow_unicode=True, sort_keys=False, width=120)


def verify_sources(manifest: dict, upstream_dir: Path) -> None:
    """Replay against a checked-out upstream snapshot, without a network dependency."""
    license_bytes = (upstream_dir / 'LICENSE').read_bytes()
    if hashlib.sha256(license_bytes).hexdigest() != manifest['upstream']['license_sha256']:
        raise ValueError('AI upstream license changed')
    for source in manifest['sources']:
        raw = (upstream_dir / source['path']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != source['sha256']:
            raise ValueError('AI upstream content changed: ' + source['path'])
        entries = [line.split('#', 1)[0].strip() for line in raw.decode().splitlines()]
        entries = {entry for entry in entries if entry}
        if entries != set(source['selected']) | set(source['omitted']):
            raise ValueError('AI source selection/omission coverage differs: ' + source['path'])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--source-dir', type=Path, help='Optional reviewed v2fly/domain-list-community checkout')
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    if args.source_dir:
        verify_sources(manifest, args.source_dir)
    body = rendered(manifest)
    if args.write:
        OUTPUT.write_text(body, encoding='utf-8', newline='\n')
    elif OUTPUT.read_text() != body:
        raise SystemExit('AI rules differ from reviewed manifest; run with --write after review')
    print(f'AI rules: {len(selected_rules(manifest))}; sources: {len(manifest["sources"])}; {"written" if args.write else "checked"}')


if __name__ == '__main__':
    main()
