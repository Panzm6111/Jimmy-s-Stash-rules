#!/usr/bin/env python3
"""Generate Mihomo config and Clash Verge profile script from the same Stash routing source."""
import argparse, copy, json, hashlib
from pathlib import Path
import yaml
ROOT=Path(__file__).resolve().parents[1]

def global_merge(source):
    """Pure overlay: keep the airport's node/provider and application settings."""
    overlay={key:copy.deepcopy(source[key]) for key in ('proxy-groups','rule-providers','rules')}
    names={group['name']:'Jimmy · '+group['name'] for group in overlay['proxy-groups']}
    for group in overlay['proxy-groups']:
        original=group['name']
        if 'use' in group:
            del group['use']
            group.update({'include-all':True,'empty-fallback':'REJECT'})
            if group['type']=='url-test' or original=='手动节点':
                group['proxies']=[name for name in group.get('proxies',[]) if name!='REJECT']
                if not group['proxies']:del group['proxies']
        if original=='总代理':
            group['proxies']=['自动节点']+[name for name in group['proxies'] if name!='自动节点']
        group['name']=names[original]
        if 'proxies' in group:group['proxies']=[names.get(name,name) for name in group['proxies']]
    for index,rule in enumerate(overlay['rules']):
        parts=rule.split(',')
        if parts[0] not in {'RULE-SET','GEOIP','MATCH'}:
            raise ValueError('Review Merge target parsing for new rule kind')
        target=1 if parts[0]=='MATCH' else 2
        parts[target]=names.get(parts[target],parts[target])
        overlay['rules'][index]=','.join(parts)
    for name,provider in overlay['rule-providers'].items():
        provider.update(proxy=names['自动节点'],
                        path='./ruleset/jimmy-merge-'+hashlib.sha256(name.encode()).hexdigest()[:12]+'.yaml')
    return overlay
def render():
    source=yaml.safe_load((ROOT/'config/stash.yaml').read_text(encoding='utf-8'))
    result={k:copy.deepcopy(v) for k,v in source.items() if k not in {'http','script-providers'}}
    result['mixed-port']=7890
    result['dns']['enable']=True
    result['proxy-providers']['机场']['path']='./providers/jimmy-airport.yaml'
    for name,p in result['rule-providers'].items():
        p.update(type='http',behavior='classical',format='yaml',interval=86400,
                 path='./ruleset/jimmy-'+hashlib.sha256(name.encode()).hexdigest()[:12]+'.yaml')
    assert result['rules']==source['rules'] and result['proxy-groups']==source['proxy-groups']
    text='# Generated by tools/build_clash.py; routing preserved; domain ad blocking only.\n# Use docs/CLASH-VERGE.md; private subscription stays local.\n'+yaml.safe_dump(result,allow_unicode=True,sort_keys=False,width=120)
    template=copy.deepcopy(result)
    del template['proxy-providers']
    # This script transforms the profile, never HTTP request/response traffic.
    script='// Generated by tools/build_clash.py. Profile transformation only, no traffic interception.\nconst JIMMY = '+json.dumps(template,ensure_ascii=False,separators=(',',':'))+''';
function main(config) {
  const providers = Object.assign({}, config["proxy-providers"] || {});
  const names = Object.keys(providers);
  const nodes = config.proxies || [];
  const own = "Jimmy-inline-nodes";
  const groupNames = JIMMY["proxy-groups"].map(g => g.name);
  if (nodes.some(n => groupNames.indexOf(n.name) >= 0)) throw new Error("Node name conflicts with a Jimmy group");
  if (nodes.length) {
    if (providers[own]) throw new Error("Reserved provider name already exists");
    providers[own] = {type:"inline", payload:nodes};
    names.push(own);
  }
  if (!names.length) throw new Error("Import your airport subscription first: no nodes or providers");
  const output = Object.assign({}, config, JSON.parse(JSON.stringify(JIMMY)));
  output["proxy-providers"] = providers;
  output.proxies = nodes;
  output["proxy-groups"].forEach(g => {if (g.use) g.use = names.slice();});
  output["rule-providers"] = Object.assign({}, config["rule-providers"] || {}, JIMMY["rule-providers"]);
  delete output.http;
  delete output["script-providers"];
  return output;
}
'''
    merge=('# Generated by tools/build_clash.py; Clash Verge global extension / Merge.\n'
           '# Keep the original airport subscription active. Paste this file into Global Extension Configuration.\n'
           '# Jimmy group prefix avoids common node-name collisions; rules refresh every 86400 seconds.\n'
           '# Structure changes require replacing this local overlay; see docs/CLASH-VERGE.md.\n'
           +yaml.safe_dump(global_merge(result),allow_unicode=True,sort_keys=False,width=120))
    return {'config/clash-verge.yaml':text,'config/clash-verge.js':script,
            'config/clash-verge-merge.yaml':merge}
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    drift=[]
    for name,body in render().items():
        path=ROOT/name
        if not path.exists() or path.read_text(encoding='utf-8')!=body:
            drift.append(name)
            if args.write:path.write_text(body,encoding='utf-8',newline='\n')
    print(str(len(drift))+' Clash files '+('written' if args.write else 'differ'))
    return 0 if args.write or not drift else 1
if __name__=='__main__':raise SystemExit(main())
