#!/usr/bin/env python3
"""Generate stable standalone Stash JS from licensed transforms and one runtime.

No module loader/network/storage is needed on the phone. Diagnostics are enabled
temporarily by the native handler argument diagnostic=1; default is silent.
"""
import argparse
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
VERSION = 'AD-20261020.1'

RUNTIME = r'''
(() => {
  let result = {}, state = 'url-unmatched';
  const version = __VERSION__, id = __ID__;
  const debug = typeof $argument === 'string' && /(?:^|&)diagnostic=1(?:&|$)/.test($argument);
  function record(x) { return !!x && typeof x === 'object' && !Array.isArray(x); }
  function successful(x, codes = [0, '0']) {
    return record(x) && x.success !== false && !x.error && !x.error_code &&
      (!Object.prototype.hasOwnProperty.call(x,'code') || codes.includes(x.code));
  }
  function mtopSuccess(x) {
    return !Object.prototype.hasOwnProperty.call(x,'ret') || (Array.isArray(x.ret) && x.ret.length > 0 && x.ret.every(v => typeof v === 'string' && /^SUCCESS(?:::|$)/.test(v)));
  }
  // Count UTF-8 bytes, not UTF-16 code units; no binary decoder assumptions.
  function oversized(s) {
    let n = 0;
    for (let i=0; i<s.length; i++) {
      const c = s.charCodeAt(i);
      if (c < 128) n++; else if (c < 2048) n += 2;
      else if (c >= 0xd800 && c <= 0xdbff && i+1 < s.length && s.charCodeAt(i+1) >= 0xdc00 && s.charCodeAt(i+1) <= 0xdfff) { n += 4; i++; }
      else n += 3;
      if (n > 2*1024*1024) return true;
    }
    return false;
  }
  try {
    const req = typeof $request === 'object' && $request ? $request : {};
    const resp = typeof $response === 'object' && $response ? $response : {};
    const url = String(req.url || '');
    if (!__PATTERNS__.some(p => new RegExp(p).test(url))) return;
    state = 'unsupported-method';
    if (!__METHODS__.includes(req.method)) return;
    state = 'body-unavailable';
    if (typeof resp.body !== 'string' || !resp.body.length) return;
    state = 'body-too-large'; if (oversized(resp.body)) return;
    state = 'http-error';
    // Stash native examples use status. Do not silently accept malformed status
    // or guess that a response with statusCode alone is a successful response.
    if (resp.status !== undefined && !/^2\d\d$/.test(String(resp.status))) return;
    if (resp.status === undefined && resp.statusCode !== undefined) { state = 'unsupported-status'; return; }
    state = 'non-json';
    if (!/^[\s]*[\[{]/.test(resp.body)) return;
    state = 'parse-error'; const obj = JSON.parse(resp.body);
    state = 'unsupported-schema'; if (!record(obj)) return;
    const before = JSON.stringify(obj);
    function transform(obj) {
__TRANSFORM__
    }
    if (!transform(obj)) return;
    const body = JSON.stringify(obj);
    state = body === before ? 'unchanged' : 'changed';
    if (state === 'changed') result = {body};
  } catch (_) {
    if (state !== 'parse-error') state = 'exception';
  } finally {
    if (debug) { try { console.log('[JimmyAds][' + id + '][' + version + '] ' + state); } catch (_) {} }
    $done(result);
  }
})();
'''

def rendered():
    result = {}
    for source in sorted((ROOT / 'tools/ad_transforms').glob('*.js')):
        name = source.stem
        module = yaml.safe_load((ROOT / f'modules/ads/{name}.stoverride').read_text())
        handlers = [h for h in module['http']['script'] if h['type'] == 'response']
        assert handlers
        text = source.read_text()
        end = text.index('*/') + 2
        header = text[:end]
        # Historical modification notes live in Git; generated output states
        # current properties without carrying obsolete "no feed/no logs" claims.
        header = '\n'.join(l for l in header.splitlines() if not any(w in l for w in ['Modified ', 'Modifications ', 'No logs', 'no logs', 'Diagnostics ', 'No generic', 'Restore upstream', 'changes;', 'no URL/', 'and durations;', 'and durations', 'response/header']))
        transform = text[end:].strip()
        body = RUNTIME.replace('__VERSION__', json.dumps(VERSION)).replace('__ID__', json.dumps(name))
        body = body.replace('__PATTERNS__', json.dumps([h['match'] for h in handlers]))
        body = body.replace('__METHODS__', json.dumps(['GET'] if name == 'bilibili' else ['GET', 'POST']))
        body = body.replace('__TRANSFORM__', '\n'.join('      ' + l for l in transform.splitlines()))
        result[f'scripts/ads/{name}.js'] = header + '\n// Generated by tools/build_ad_scripts.py; version ' + VERSION + '\n' + body
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    drift = []
    for name, body in rendered().items():
        p = ROOT / name
        if not p.exists() or p.read_text() != body:
            drift.append(name)
            if args.write: p.write_text(body, encoding='utf-8', newline='\n')
    print(f'{len(drift)} script files ' + ('written' if args.write else 'differ'))
    return 0 if args.write or not drift else 1

if __name__ == '__main__': raise SystemExit(main())
