#!/usr/bin/env python3
"""Build an opt-in, metadata-only HTTP probe from actual maintained matches.

Use in isolation with normal HTTP actions disabled in a temporary local copy.
It never changes requests,
reads bodies/headers, makes requests, or writes device storage.
"""
import argparse
import json
from pathlib import Path
import re
import yaml
from build_ad_scripts import VERSION

ROOT = Path(__file__).resolve().parents[1]
RAW = 'https://raw.githubusercontent.com/Panzm6111/Jimmy-s-Stash-rules/main/'

def rendered():
    hosts, routes = set(), []
    for path in sorted((ROOT / 'modules/ads').glob('*.stoverride')):
        if path.stem == 'expanded': continue
        module = yaml.safe_load(path.read_text())
        http = module.get('http', {})
        hosts.update(http.get('mitm', []))
        for r in http.get('url-rewrite', []): routes.append({'id':path.stem, 'match':r.rsplit(' - ',1)[0]})
        for r in http.get('script', []): routes.append({'id':path.stem, 'match':r['match']})
    script = '''/* SPDX-License-Identifier: MIT
 * Generated metadata-only observer. Match references retain their source notices
 * in modules/ads and research/ad-catalog.json. Never logs request values.
 */
(() => {
  try {
    const req = typeof $request === 'object' && $request ? $request : {};
    const url = String(req.url || '');
    const routes = __ROUTES__;
    const hit = routes.find(r => new RegExp(r.match).test(url));
    console.log('[JimmyAds][' + (hit ? hit.id : 'probe') + '][__VERSION__] ' + (hit ? 'request-url-matched' : 'request-url-unmatched'));
  } catch (_) { try { console.log('[JimmyAds][probe][__VERSION__] exception'); } catch (_) {} }
  finally { $done({}); }
})();
'''.replace('__ROUTES__', json.dumps(routes,ensure_ascii=False)).replace('__VERSION__', VERSION)
    config = {'name':'Jimmy 广告诊断（临时、只观察）',
              'desc':VERSION+'；仅临时排查：先在本地诊断副本停用正式HTTP动作并将广告组设为DIRECT，再单独启用探针。用完恢复原配置。步骤见docs/ADBLOCKING.md；无日志不能证明未进MITM。',
              'http':{'mitm':sorted(hosts), 'script':[{
                  'match':r'^https://(?:'+ '|'.join(re.escape(h) for h in sorted(hosts)) +r')(?::443)?/',
                  'name':'jimmy_ads_probe','type':'request','require-body':False,'timeout':5}]},
              'script-providers':{'jimmy_ads_probe':{'url':RAW+'scripts/ads/probe.js','interval':86400}}}
    return {'scripts/ads/probe.js':script,
            'modules/diagnostics/ads.stoverride':'# SPDX-License-Identifier: MIT\n# Generated by tools/build_ad_diagnostics.py; do not use as an ad-block module.\n'+yaml.safe_dump(config,allow_unicode=True,sort_keys=False,width=120)}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');args=p.parse_args()
    drift=[]
    for name,body in rendered().items():
        path=ROOT/name
        if not path.exists() or path.read_text()!=body:
            drift.append(name)
            if args.write: path.parent.mkdir(parents=True,exist_ok=True);path.write_text(body, encoding='utf-8', newline='\n')
    print(f'{len(drift)} probe files '+('written' if args.write else 'differ'))
    return 0 if args.write or not drift else 1

if __name__=='__main__': raise SystemExit(main())
